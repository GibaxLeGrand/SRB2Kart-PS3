// 2026-08-26 -- PS3 wall-clock profiler. MEASUREMENT ONLY: nothing in here
// changes how the game paces itself. Two questions to settle before touching
// any timing code:
//
//  1. Which clock sources on this toolchain actually work? gettimeofday() is
//     suspect: PS3DK's runtime/lv2/librt/gettod.c:19 calls
//     sysGetCurrentTime(ptimeval, ptimezone) -- i.e. it hands the whole
//     struct timeval in as the "sec" out-pointer and NULL (the timezone arg)
//     as the "nsec" out-pointer, so tv_usec is never written. Every fork of
//     the same tree does "tv_sec = sec; tv_usec = nsec/1000;" instead.
//     SDL_GetTicks()/SDL_GetPerformanceCounter() sit on top of that, and so
//     does every tic-pacing wait loop in the game.
//
//  2. How much of a frame goes into the per-frame debug file writes left over
//     from the flip-#555 investigation? There are 8 fopen/fprintf/fflush/
//     fclose cycles per frame here plus 8 more in I_FinishUpdate, all
//     appending to files on the emulated HDD.
//
// Everything is timed on the PPU timebase (mftb), which is independent of
// both suspects.
// ---------------------------------------------------------------------------
#include <sys/systime.h>   // sysGetCurrentTime, sysGetTimebaseFrequency, sysUsleep
#include <sys/time.h>      // gettimeofday
#include <sys/thread.h>    // sysThreadGetStackInformation -- see the stack watermark below
#include <unistd.h>        // usleep

// ---------------------------------------------------------------------------
// 2026-08-26 -- stack watermark.
//
// cdb caught the RPCS3 crash as a host NX fault with RIP = 0: guest code
// branched through a null code pointer. A smashed return address is the
// natural way to get one, and running out of stack is the natural way to get
// that. The suspicion is structural rather than a hunch: TanakaDOOM-cGcm runs
// the same toolchain and the same kind of software renderer on PS3 without
// dying, and the one thing it does not have is SDL -- whose PSL1GHT backend
// hardcodes a 16KB stack for every thread it creates
// (~/SDL2_PSL1GHT/src/thread/psl1ght/SDL_systhread.c:73, "size_t stack_size =
// 0x4000"). SRB2's renderer recurses through R_RenderBSPNode and its thinkers
// call into each other, and "how much stack do we actually use" has never been
// answered on this port.
//
// So measure it. sysThreadGetStackInformation (syscall 49, verified in
// $PS3DEV/ps3dk/ppu/include/sys/thread.h) gives the running thread's stack
// buffer; PS3_StackTouch() keeps the lowest stack pointer ever seen and every
// psdebugS.txt line carries the peak. A compare and a store per call, so it is
// affordable even inside the BSP recursion.
// ---------------------------------------------------------------------------
static u32 ps3stack_base = 0;
static u32 ps3stack_size = 0;
static u32 ps3stack_min = 0xFFFFFFFFu;

static void PS3_StackInit(void)
{
	sys_ppu_thread_stack_t si;

	si.pst_addr = 0;
	si.pst_size = 0;

	if (sysThreadGetStackInformation(&si) == 0)
	{
		ps3stack_base = (u32)(uintptr_t)si.pst_addr;
		ps3stack_size = (u32)si.pst_size;
	}
}

void PS3_StackTouch(void)
{
	u32 sp = (u32)(uintptr_t)__builtin_frame_address(0);

	if (sp < ps3stack_min)
		ps3stack_min = sp;
}

// Same idiom as the toolchain's __gettime() macro in
// $PS3DEV/ps3dk/ppu/include/sys/ppu-asm.h (mftb, retried while it reads 0).
// Written out here rather than including that header, which would also drag
// its bswap static-inline block into this translation unit.
static inline u64 ps3prof_tb(void)
{
	unsigned long long tb;
	__asm__ __volatile__(
		"1:\n\t"
		"mftb  %[t]\n\t"
		"cmpwi 7,%[t],0\n\t"
		"beq-  7,1b"
		: [t] "=r"(tb) : : "cr7");
	return (u64)tb;
}

static u64 ps3prof_tbfreq = 79800000ULL;   // replaced with the real value at probe time
#define PS3PROF_TB2US(d) (((u64)(d)) * 1000000ULL / ps3prof_tbfreq)

#define PS3PROF_FRAMES  500  // main-loop iterations recorded before the dump
#define PS3PROF_WARMUP  200  // frames before this are excluded from the averages
#define PS3PROF_BLOCK   100  // after warmup, traces alternate on/off per block

// The debug writes are A/B'd in interleaved blocks rather than at a single
// split point: the intro plays out inside the first few hundred main-loop
// iterations and is far more expensive per frame than the title screen, so a
// single "on then off" split would price that transition instead of the
// writes.
// Which families of per-frame debug file writes are enabled, as a bitmask.
// Read here and by i_video.c, d_clisrv.c, d_net.c and g_game.c (those use the
// bit values directly, since this is a debug-only switch not worth a header).
//
// Measured 2026-08-26: one fopen/fprintf/fflush/fclose cycle on the emulated
// HDD costs 903us, and the ~16 per frame cost 9.7ms -- 48fps with them all on
// versus 91fps with them all off, over 400 title-screen frames each. So the
// shipping value is 0.
//
// It is a bitmask rather than a flag because these writes turn out to keep the
// game alive: with all of them off RPCS3 segfaults two intro tics in, with all
// of them on the game reaches the title screen. Same signature as the
// ps3rsxnudge note in i_video.c -- interleaved real syscalls between the RSX
// sub-calls mask the fault, while a plain delay does not (four negative
// isolation results on delay alone, 23/08). Enabling one family at a time
// narrows down where the missing serialisation actually is.
#define PS3TRACE_LOOP     1	// ps3mloop, D_SRB2Loop, 8 sites/frame, no RSX nearby
#define PS3TRACE_DISPLAY  2	// ps3d, D_Display, up to 19 sites/frame
#define PS3TRACE_FINISH   4	// ps3fu, I_FinishUpdate, 8 sites/frame, closest to the gcm calls
#define PS3TRACE_LOGIC    8	// ps3cs / ps3n / ps3gt2, game logic, furthest from the RSX
#define PS3TRACE_DISPLAY_SYNC 16	// ps3d sites issue a "sync" barrier instead of writing
#define PS3TRACE_STATE       32	// psdebugS.txt game-state log (cheap, see PS3_StateWatch)
#define PS3TRACE_FIFO        64	// command-FIFO watch in i_video_ps3_gcm.c (cheap, ~30 lines/lap)
#define PS3TRACE_MARK       128	// PS3_Mark() checkpoints on one-shot paths (cheap, ~10 lines)

// Shipping value. DISPLAY_SYNC is a WORKAROUND, not a fix: without some
// serialisation at the ps3d sites the game does not survive two intro tics,
// and nobody has established why. STATE is the psdebugS.txt progress log.
// The file-writing families (LOOP/DISPLAY/FINISH/LOGIC) stay off -- 903us each.
//
// 2026-08-26 ~17:00: FIFO added, and the answer came back negative -- the FIFO
// wraps cleanly every ~250 flips and the crash lands 145 frames off one. Kept
// on because it is nearly free and it dates the wraps on the same timeline.
// ~18:50: MARK added to walk the title-screen -> attract-demo transition.
int ps3_debugtrace = PS3TRACE_DISPLAY_SYNC | PS3TRACE_STATE | PS3TRACE_FIFO | PS3TRACE_MARK;


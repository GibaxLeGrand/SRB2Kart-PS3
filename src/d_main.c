static u64 ps3state_epoch_tb = 0;

static void PS3_StateLine(u64 now_us, unsigned int frame, unsigned int frame_us, const char *what)
{
	FILE *f = fopen(PS3_DebugPath("psdebugS.txt"), "a");
	unsigned int fps_x100;

	if (!f)
		return;

	fps_x100 = frame_us ? (unsigned int)(100000000UL / frame_us) : 0;

	fprintf(f, "[%4llu.%03llus f%-6u tic%-7u %3u.%02u fps] %s\n",
		(unsigned long long)(now_us / 1000000ULL),
		(unsigned long long)((now_us / 1000ULL) % 1000ULL),
		frame, (unsigned int)gametic,
		fps_x100 / 100, fps_x100 % 100,
		what);

	// Stack watermark on the same line: how deep we have ever gone, and how
	// much room was left at that point. If "left" trends towards zero, the
	// null-code-pointer crash is stack exhaustion and we are done guessing.
	if (ps3stack_size != 0)
	{
		u32 top = ps3stack_base + ps3stack_size;
		u32 sp = (u32)(uintptr_t)__builtin_frame_address(0);
		u32 peak = (ps3stack_min == 0xFFFFFFFFu) ? sp : ps3stack_min;

		fprintf(f, "        stack base=%08x size=%u  now=%u  PEAK=%u  left_at_peak=%d\n",
			(unsigned)ps3stack_base, (unsigned)ps3stack_size,
			(unsigned)(top - sp), (unsigned)(top - peak),
			(int)(peak - ps3stack_base));
	}

	fflush(f);
	fclose(f);
}

// 2026-08-26 -- one-off checkpoint on the same psdebugS.txt timeline.
//
// For tracing a path that runs once, where a per-frame trace family would be
// both too expensive and too noisy. Written for the title-screen -> attract
// demo transition, which three runs have now pinned as the place RPCS3 dies:
// the last heartbeat is always tic 736, and the demo starts at tic 770.
//
// Gated by PS3TRACE_MARK so it costs nothing when off, and it is on a
// once-per-transition path rather than a per-frame one, so the 903us a debug
// write costs is affordable here in a way it is not in D_Display.
static unsigned int ps3state_frame = 0;
static unsigned int ps3state_frame_us = 0;

// ---------------------------------------------------------------------------
// 2026-08-26 -- indirect action-call guard.
//
// The crash signature is a host NX fault at RIP = 0 on the PPU thread: guest
// code jumping through a bad code pointer. Everything else is now excluded --
// the stack peaks at 9312 bytes of 1MB, the zone heap validates clean at every
// phase of P_SetupLevel, and states[] is intact in the linked binary.
//
// So look at the places that actually jump through a pointer without checking
// it. SRB2 has eight, all on the level/gameplay path, and four of them index
// states[] with a number that comes from state data rather than from code
// (A_DualAction, A_RemoteAction and friends read it out of var1/var2).
//
// This reports the offending target and skips the call instead of taking it.
// Three possible outcomes, all of them useful: lines appear and name the site;
// the crash disappears, which proves it; or nothing appears and all eight
// sites are cleared.
//
// The image is at 0x10230 (.text) through 0x39c704 (end of .opd), so a real
// function pointer is 4-byte aligned and inside [0x10000, 0x3a0000).
#define PS3_CODE_LO 0x00010000u
#define PS3_CODE_HI 0x003a0000u

// 2026-08-27 -- the same pointer sanity as PS3_BadAction, minus the state
// number, for indirect calls that are not state actions. P_RunThinkers is the
// one that matters: thinker_t.function.acp1 is called directly for every live
// object every tic, and it was the last unguarded indirect call in the game.
int PS3_BadFunc(const char *where, void *fn)
{
	static int reported = 0;
	u32 a = (u32)(uintptr_t)fn;
	const char *why = NULL;
	char line[192];

	if (fn == NULL)
		why = "NULL function";
	else if ((a & 3u) != 0u)
		why = "misaligned function pointer";
	else if (a < PS3_CODE_LO || a >= PS3_CODE_HI)
		why = "function pointer outside the image";

	if (why == NULL)
		return 0;

	if (reported < 24)
	{
		reported++;
		snprintf(line, sizeof line, "*** BAD CALL *** %s: fn=%08x -- %s (skipped)",
			where, (unsigned)a, why);
		PS3_Mark(line);
		fprintf(stderr, "[PS3] %s\n", line);
	}

	return 1;
}

int PS3_BadAction(const char *where, INT32 statenum, void *fn)
{
	static int reported = 0;
	u32 a = (u32)(uintptr_t)fn;
	const char *why = NULL;
	char line[192];

	if (statenum < 0 || statenum >= NUMSTATES)
		why = "state number out of range";
	else if (fn == NULL)
		why = "NULL action";
	else if ((a & 3u) != 0u)
		why = "misaligned action pointer";
	else if (a < PS3_CODE_LO || a >= PS3_CODE_HI)
		why = "action pointer outside the image";

	if (why == NULL)
		return 0;

	if (reported < 24)
	{
		reported++;
		snprintf(line, sizeof line, "*** BAD ACTION CALL *** %s: state=%d fn=%08x -- %s (skipped)",
			where, (int)statenum, (unsigned)a, why);
		PS3_Mark(line);
		fprintf(stderr, "[PS3] %s\n", line);
	}

	return 1;
}

// 2026-08-26 -- debug files follow srb2home instead of a hardcoded path.
// D_Home() now points at the package USRDIR when the title is installed, so
// on real hardware these land next to the game instead of failing to open in
// a directory that does not exist. Returns a rotating set of static buffers
// so a caller can hold two paths at once without surprises.
const char *PS3_DebugPath(const char *name)
{
	static char buf[4][320];
	static int slot = 0;
	char *out;

	slot = (slot + 1) & 3;
	out = buf[slot];

	// srb2home keeps its "." default until D_SRB2Main reaches the config
	// section, and the earliest traces run before that -- i_main.c writes
	// "M1 before D_SRB2Main" already. Under RPCS3 a relative path landed in
	// the right place anyway, because the emulator's working directory is the
	// EBOOT's own directory; launched from a real XMB it is not, so those
	// traces were silently lost. They are exactly the ones worth having when a
	// boot fails early, which is what a first hardware test tends to do.
	if (srb2home[0] == '\0' || (srb2home[0] == '.' && srb2home[1] == '\0'))
	{
		snprintf(out, sizeof buf[0], "%s/%s", PS3_INSTALLDIR, name);
		return out;
	}

	snprintf(out, sizeof buf[0], "%s%s%s", srb2home,
		(srb2home[0] && srb2home[strlen(srb2home) - 1] == '/') ? "" : "/", name);
	return out;
}

void PS3_Mark(const char *what)
{
	u64 now_us;

	if (!(ps3_debugtrace & PS3TRACE_MARK))
		return;

	if (ps3state_epoch_tb == 0)
		ps3state_epoch_tb = ps3prof_tb();
	now_us = PS3PROF_TB2US(ps3prof_tb() - ps3state_epoch_tb);

	PS3_StateLine(now_us, ps3state_frame, ps3state_frame_us, what);
}

static void PS3_StateWatch(unsigned int frame, unsigned int frame_us)
{
	static int started = 0;
	static gamestate_t last_gs;
	static gameaction_t last_ga;
	static int last_demo;
	static INT16 last_map;
	static u64 next_beat_us;
	char line[192];
	u64 now_us;

	ps3state_frame = frame;
	ps3state_frame_us = frame_us;

	if (!(ps3_debugtrace & PS3TRACE_STATE))
		return;

	if (ps3state_epoch_tb == 0)
		ps3state_epoch_tb = ps3prof_tb();
	now_us = PS3PROF_TB2US(ps3prof_tb() - ps3state_epoch_tb);

	if (!started)
	{
		started = 1;
		PS3_StackInit();
		last_gs = gamestate;
		last_ga = gameaction;
		last_demo = demo.playback ? 1 : 0;
		last_map = gamemap;
		next_beat_us = now_us;
		snprintf(line, sizeof line, "start   gamestate=%s gamemap=%d",
			PS3_GameStateName(gamestate), (int)gamemap);
		PS3_StateLine(now_us, frame, frame_us, line);
		return;
	}

	if (gamestate != last_gs)
	{
		snprintf(line, sizeof line, "gamestate  %s -> %s",
			PS3_GameStateName(last_gs), PS3_GameStateName(gamestate));
		PS3_StateLine(now_us, frame, frame_us, line);
		last_gs = gamestate;
	}

	if (gameaction != last_ga)
	{
		snprintf(line, sizeof line, "gameaction %s -> %s",
			PS3_GameActionName(last_ga), PS3_GameActionName(gameaction));
		PS3_StateLine(now_us, frame, frame_us, line);
		last_ga = gameaction;
	}

	if ((demo.playback ? 1 : 0) != last_demo)
	{
		last_demo = demo.playback ? 1 : 0;
		snprintf(line, sizeof line, "demo playback %s", last_demo ? "STARTED" : "stopped");
		PS3_StateLine(now_us, frame, frame_us, line);
	}

	if (gamemap != last_map)
	{
		snprintf(line, sizeof line, "gamemap %d -> %d", (int)last_map, (int)gamemap);
		PS3_StateLine(now_us, frame, frame_us, line);
		last_map = gamemap;
	}

	if (now_us >= next_beat_us)
	{
		next_beat_us = now_us + 1000000ULL;	// one line per second
		snprintf(line, sizeof line, "heartbeat  %s%s",
			PS3_GameStateName(gamestate), demo.playback ? " (demo)" : "");
		PS3_StateLine(now_us, frame, frame_us, line);

		// Once a second, validate the whole zone heap. GS_LEVEL is one of the
		// three places RPCS3 has died, so the level-load probes in
		// P_SetupLevel are not enough on their own.
		PS3_HeapProbe("heartbeat");
	}
}

static void PS3_ProfRecord(int iter, unsigned int total, unsigned int tics,
	unsigned int disp, unsigned int slp)
{
	int i;

	if (iter < 1 || iter > PS3PROF_FRAMES)
		return;

	i = iter - 1;
	ps3prof_total[i] = total;
	ps3prof_tics[i] = tics;
	ps3prof_disp[i] = disp;
	ps3prof_slp[i] = slp;
	ps3prof_on[i] = (unsigned char)(ps3_debugtrace ? 1 : 0);

	if (iter == PS3PROF_FRAMES && !ps3prof_dumped)
	{
		ps3prof_dumped = 1;
		PS3_ProfDump();
	}
}

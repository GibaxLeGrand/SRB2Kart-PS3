void D_SRB2Loop(void)
{
	tic_t entertic = 0, oldentertics = 0, realtics = 0, rendertimeout = INFTICS;
	double deltatics = 0.0;
	double deltasecs = 0.0;

	boolean interp = false;
	boolean doDisplay = false;

	if (dedicated)
		server = true;

	// Pushing of + parameters is now done back in D_SRB2Main, not here.

#ifdef _WINDOWS
	CONS_Printf("I_StartupMouse()...\n");
	I_DoStartupMouse();
#endif

	I_UpdateTime(cv_timescale.value);
	oldentertics = I_GetTime();

	// end of loading screen: CONS_Printf() will no more call FinishUpdate()
	con_startup = false;

	// make sure to do a d_display to init mode _before_ load a level
	ps3m("L1 before SCR_SetMode");
	SCR_SetMode(); // change video mode
	ps3m("L2 after SCR_SetMode, before SCR_Recalc");
	SCR_Recalc();
	ps3m("L3 after SCR_Recalc");

	// Check and print which version is executed.
	// Use this as the border between setup and the main game loop being entered.
	CONS_Printf(
	"===========================================================================\n"
	"                   We hope you enjoy this game as\n"
	"                     much as we did making it!\n"
	"===========================================================================\n");

	// hack to start on a nice clear console screen.
	COM_ImmedExecute("cls;version");

	ps3m("L4 before KARTKREW patch draw");
	if (rendermode == render_soft)
	{
		ps3m("L5 before W_GetNumForName(KARTKREW)");
		{
			lumpnum_t kklump = W_GetNumForName("KARTKREW");
			ps3m("L6 before W_CacheLumpNum(KARTKREW)");
			{
				patch_t *kkpatch = (patch_t *)W_CacheLumpNum(kklump, PU_CACHE);
				ps3m("L7 before V_DrawFixedPatch");
				V_DrawFixedPatch(0, 0, FRACUNIT/2, 0, kkpatch, NULL);
				ps3m("L8 after V_DrawFixedPatch");
			}
		}
	}
	ps3m("L9 before I_FinishUpdate");
	I_FinishUpdate(); // page flip or blit buffer
	ps3m("L10 after I_FinishUpdate, before main loop");

	for (;;)
	{
		// capbudget is the minimum precise_t duration of a single loop iteration
		precise_t capbudget;
		precise_t enterprecise = I_GetPreciseTime();
		precise_t finishprecise = enterprecise;
#ifdef _PS3
		static int ps3loopiter = 0;
		boolean ps3trace;
		u64 ps3p_iter0, ps3p_a = 0, ps3p_b = 0;
		unsigned int ps3p_tics = 0, ps3p_disp = 0, ps3p_slp = 0;
		ps3loopiter++;
		ps3p_iter0 = ps3prof_tb();
		// The alternating on/off A/B that used to live here has served its
		// purpose (9.7ms per frame, 48fps vs 91fps) -- ps3_debugtrace now just
		// stays at whatever it is initialised to, off by default.
		ps3trace = ((ps3_debugtrace & PS3TRACE_LOOP) && ps3loopiter <= 3000);
		if (ps3loopiter == 1) { ps3m("L11 first main loop iteration entered"); PS3_ClockProbe(); }
		if (ps3trace) ps3mloop(ps3loopiter, "top of iteration");
#endif

		{
			// Casting the return value of a function is bad practice (apparently)
			double budget = round((1.0 / R_GetFramerateCap()) * I_GetPrecisePrecision());
			capbudget = (precise_t) budget;
		}

		I_UpdateTime(cv_timescale.value);

		if (lastwipetic)
		{
			oldentertics = lastwipetic;
			lastwipetic = 0;
		}

		// get real tics
		entertic = I_GetTime();
		realtics = entertic - oldentertics;
		oldentertics = entertic;
#ifdef _PS3
		if (realtics != 0) ps3mloop(ps3loopiter, va("RT realtics=%lu entertic=%lu", (unsigned long)realtics, (unsigned long)entertic));
#endif

		if (demo.playback && gamestate == GS_LEVEL)
		{
			// Nicer place to put this.
			realtics = realtics * cv_playbackspeed.value;
		}

#ifdef DEBUGFILE
		if (!realtics)
			if (debugload)
				debugload--;
#endif

		interp = R_UsingFrameInterpolation() && !dedicated;
		doDisplay = false;

#ifdef HW3SOUND
		HW3S_BeginFrameUpdate();
#endif

		refreshdirmenu = 0; // not sure where to put this, here as good as any?

		if (realtics > 0 || singletics)
		{
			// don't skip more than 10 frames at a time
			// (fadein / fadeout cause massive frame skip!)
			if (realtics > 8)
				realtics = 1;

			// process tics (but maybe not if realtic == 0)
#ifdef _PS3
			ps3p_a = ps3prof_tb();
#endif
			TryRunTics(realtics);
#ifdef _PS3
			ps3p_b = ps3prof_tb();
			ps3p_tics = (unsigned int)PS3PROF_TB2US(ps3p_b - ps3p_a);
			if (ps3trace) ps3mloop(ps3loopiter, "after TryRunTics");
#endif

			if (lastdraw || singletics || gametic > rendergametic)
			{
				rendergametic = gametic;
				rendertimeout = entertic + TICRATE/17;

				doDisplay = true;
			}
			else if (rendertimeout < entertic) // in case the server hang or netsplit
			{
				doDisplay = true;
			}

			renderisnewtic = true;
		}
		else
		{
			renderisnewtic = false;
		}

		if (interp)
		{
			renderdeltatics = FLOAT_TO_FIXED(deltatics);

			if (!(paused || P_AutoPause()) && deltatics < 1.0 && !hu_stopped)
			{
				rendertimefrac = g_time.timefrac;
			}
			else
			{
				rendertimefrac = FRACUNIT;
			}
		}
		else
		{
			renderdeltatics = realtics * FRACUNIT;
			rendertimefrac = FRACUNIT;
		}

		if (interp || doDisplay)
		{
#ifdef _PS3
			if (ps3trace) ps3mloop(ps3loopiter, "before D_Display");
			ps3p_a = ps3prof_tb();
#endif
			D_Display();
#ifdef _PS3
			ps3p_b = ps3prof_tb();
			ps3p_disp = (unsigned int)PS3PROF_TB2US(ps3p_b - ps3p_a);
			if (ps3trace) ps3mloop(ps3loopiter, "after D_Display");
#endif
		}

		// Only take screenshots after drawing.
		if (moviemode)
			M_SaveFrame();
		if (takescreenshot)
			M_DoScreenShot();

		// consoleplayer -> displayplayers (hear sounds from viewpoint)
		S_UpdateSounds(); // move positional sounds
#ifdef _PS3
		if (ps3trace) ps3mloop(ps3loopiter, "after S_UpdateSounds");
#endif

		// check for media change, loop music..
		I_UpdateCD();
#ifdef _PS3
		if (ps3trace) ps3mloop(ps3loopiter, "after I_UpdateCD");
#endif

#ifdef HW3SOUND
		HW3S_EndFrameUpdate();
#endif

#ifdef HAVE_BLUA
		LUA_Step();
#endif

#ifdef HAVE_DISCORDRPC
		if (! dedicated)
		{
			Discord_RunCallbacks();
		}
#endif

		// Fully completed frame made.
#ifdef _PS3
		ps3p_a = ps3prof_tb();
#endif
		finishprecise = I_GetPreciseTime();
		if (!singletics)
		{
			INT64 elapsed = (INT64)(finishprecise - enterprecise);

			// in the case of "match refresh rate" + vsync, don't sleep at all
			const boolean vsync_with_match_refresh = cv_vidwait.value && cv_fpscap.value == 0;

			if (elapsed > 0 && (INT64)capbudget > elapsed && !vsync_with_match_refresh)
			{
				I_SleepDuration(capbudget - (finishprecise - enterprecise));
			}
		}
#ifdef _PS3
		ps3p_b = ps3prof_tb();
		ps3p_slp = (unsigned int)PS3PROF_TB2US(ps3p_b - ps3p_a);
#endif
		// Capture the time once more to get the real delta time.
		finishprecise = I_GetPreciseTime();
		deltasecs = (double)((INT64)(finishprecise - enterprecise)) / I_GetPrecisePrecision();
		deltatics = deltasecs * NEWTICRATE;
#ifdef _PS3
		if (ps3trace) ps3mloop(ps3loopiter, "end of iteration");
		{
			unsigned int ps3p_total = (unsigned int)PS3PROF_TB2US(ps3prof_tb() - ps3p_iter0);

			PS3_ProfRecord(ps3loopiter, ps3p_total, ps3p_tics, ps3p_disp, ps3p_slp);
			PS3_StateWatch((unsigned int)ps3loopiter, ps3p_total);
		}
#endif
	}
}

